/** Count leaf string/primitive values per top-level namespace */
function countNamespaceKeys(obj) {
  const counts = {};
  for (const [ns, value] of Object.entries(obj)) {
    counts[ns] = countLeaves(value);
  }
  return counts;
}

function countLeaves(value) {
  if (value === null || typeof value !== 'object') return 1;
  if (Array.isArray(value)) {
    return value.reduce((sum, item) => sum + countLeaves(item), 0);
  }
  return Object.values(value).reduce((sum, v) => sum + countLeaves(v), 0);
}

function printSummaryTable(enCounts, frCounts, swCounts) {
  const namespaces = Object.keys(enCounts).sort();
  const col = (s, w) => String(s).padStart(w);
  const w = Math.max(12, ...namespaces.map((n) => n.length));
  console.log('\nKey counts per namespace (leaf values):\n');
  console.log(`${col('Namespace', w)}  ${col('en', 6)}  ${col('fr', 6)}  ${col('sw', 6)}  Match`);
  console.log(`${'-'.repeat(w)}  ${'-'.repeat(6)}  ${'-'.repeat(6)}  ${'-'.repeat(6)}  -----`);
  let totalEn = 0;
  let totalFr = 0;
  let totalSw = 0;
  for (const ns of namespaces) {
    const e = enCounts[ns];
    const f = frCounts[ns];
    const s = swCounts[ns];
    totalEn += e;
    totalFr += f;
    totalSw += s;
    const match = e === f && f === s ? '✓' : '✗';
    console.log(`${col(ns, w)}  ${col(e, 6)}  ${col(f, 6)}  ${col(s, 6)}  ${match}`);
  }
  console.log(`${'-'.repeat(w)}  ${'-'.repeat(6)}  ${'-'.repeat(6)}  ${'-'.repeat(6)}  -----`);
  const allMatch = totalEn === totalFr && totalFr === totalSw;
  console.log(`${col('TOTAL', w)}  ${col(totalEn, 6)}  ${col(totalFr, 6)}  ${col(totalSw, 6)}  ${allMatch ? '✓' : '✗'}`);
}

