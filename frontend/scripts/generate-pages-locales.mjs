const { fr: frDict, sw: swDict } = JSON.parse(
  readFileSync(join(__dirname, 'string-dict.json'), 'utf8')
);

function translateTree(obj, dict) {
  if (typeof obj === 'string') return dict[obj] ?? obj;
  if (Array.isArray(obj)) return obj.map((item) => translateTree(item, dict));
  if (obj && typeof obj === 'object') {
    return Object.fromEntries(
      Object.entries(obj).map(([key, value]) => [key, translateTree(value, dict)])
    );
  }
  return obj;
}

const fr = translateTree(en, frDict);
const sw = translateTree(en, swDict);

function writeLocale(code, data) {
  const dir = join(LOCALES_DIR, code);
  mkdirSync(dir, { recursive: true });
  const filePath = join(dir, 'pages.json');
  writeFileSync(filePath, `${JSON.stringify(data, null, 2)}\n`, 'utf8');
  const bytes = Buffer.byteLength(JSON.stringify(data));
  console.log(`Wrote ${filePath} (${bytes.toLocaleString()} bytes)`);
}

